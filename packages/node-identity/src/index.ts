import {
	createHash,
	createPrivateKey,
	createPublicKey,
	generateKeyPairSync,
	sign as nodeSign,
	verify as nodeVerify,
	type KeyObject,
} from "node:crypto";
import { chmodSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Node identity: an Ed25519 keypair created on first boot. The fingerprint (SHA-256 of the raw
 * 32-byte public key, lowercase hex) is the node's durable cryptographic identity and the node id
 * is derived from it. `sign`/`verify` are the primitives the node-to-node protocol (`/api/v1`,
 * later milestones) builds signed requests on.
 */

const PRIVATE_KEY_FILE = "ed25519.key";
const PUBLIC_KEY_FILE = "ed25519.pub";
const NODE_ID_PREFIX = "node_";
const NODE_ID_HEX_CHARS = 16;

export interface NodeIdentity {
	/** Stable id derived from the fingerprint: `node_` + first 16 hex chars. */
	readonly nodeId: string;
	/** SHA-256 of the raw public key, lowercase hex (64 chars). */
	readonly fingerprint: string;
	/** Raw 32-byte Ed25519 public key, base64. */
	readonly publicKey: string;
	/** Directory holding the key files. */
	readonly identityDir: string;
	/** True when the keypair was generated by this call (first boot). */
	readonly created: boolean;
	/** Ed25519 signature over `message`, base64. */
	sign(message: Uint8Array | string): string;
}

export function fingerprintOf(rawPublicKey: Uint8Array): string {
	return createHash("sha256").update(rawPublicKey).digest("hex");
}

export function nodeIdFromFingerprint(fingerprint: string): string {
	return `${NODE_ID_PREFIX}${fingerprint.slice(0, NODE_ID_HEX_CHARS)}`;
}

function toBytes(message: Uint8Array | string): Uint8Array {
	return typeof message === "string" ? new TextEncoder().encode(message) : message;
}

function rawPublicKeyOf(key: KeyObject): Buffer {
	const jwk = key.export({ format: "jwk" });
	if (jwk.kty !== "OKP" || jwk.crv !== "Ed25519" || typeof jwk.x !== "string") {
		throw new Error("Not an Ed25519 public key");
	}
	return Buffer.from(jwk.x, "base64url");
}

function publicKeyFromRaw(raw: Buffer): KeyObject {
	if (raw.length !== 32) throw new Error(`Ed25519 public key must be 32 bytes, got ${raw.length}`);
	return createPublicKey({ key: { kty: "OKP", crv: "Ed25519", x: raw.toString("base64url") }, format: "jwk" });
}

/**
 * Verify an Ed25519 signature. `publicKey` and `signature` are base64. Never throws on malformed
 * input; returns false instead so callers can treat every failure as "unauthenticated".
 */
export function verifySignature(input: { publicKey: string; message: Uint8Array | string; signature: string }): boolean {
	try {
		const key = publicKeyFromRaw(Buffer.from(input.publicKey, "base64"));
		return nodeVerify(null, toBytes(input.message), key, Buffer.from(input.signature, "base64"));
	} catch {
		return false;
	}
}

/** Fingerprint of a base64 raw public key (as exchanged between nodes). */
export function fingerprintOfPublicKey(publicKeyBase64: string): string {
	return fingerprintOf(Buffer.from(publicKeyBase64, "base64"));
}

function identityFrom(identityDir: string, privateKey: KeyObject, created: boolean): NodeIdentity {
	const raw = rawPublicKeyOf(createPublicKey(privateKey));
	const fingerprint = fingerprintOf(raw);
	return {
		nodeId: nodeIdFromFingerprint(fingerprint),
		fingerprint,
		publicKey: raw.toString("base64"),
		identityDir,
		created,
		sign: (message) => nodeSign(null, toBytes(message), privateKey).toString("base64"),
	};
}

/**
 * Load the node keypair from `<dataDir>/identity/`, generating it on first boot. The private key
 * file is written with mode 0600 (directory 0700); a looser mode found on load is tightened.
 */
export function loadOrCreateIdentity(options: { dataDir: string }): NodeIdentity {
	const identityDir = join(options.dataDir, "identity");
	const privatePath = join(identityDir, PRIVATE_KEY_FILE);
	const publicPath = join(identityDir, PUBLIC_KEY_FILE);
	mkdirSync(identityDir, { recursive: true, mode: 0o700 });

	if (!existsSync(privatePath)) {
		const { privateKey, publicKey } = generateKeyPairSync("ed25519");
		try {
			// `wx` makes concurrent first boots race safely: the loser reads the winner's key.
			writeFileSync(privatePath, privateKey.export({ format: "pem", type: "pkcs8" }), { mode: 0o600, flag: "wx" });
			writeFileSync(publicPath, publicKey.export({ format: "pem", type: "spki" }), { mode: 0o644 });
			return identityFrom(identityDir, privateKey, true);
		} catch (error) {
			if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error;
		}
	}

	if (process.platform !== "win32" && (statSync(privatePath).mode & 0o077) !== 0) chmodSync(privatePath, 0o600);
	const privateKey = createPrivateKey(readFileSync(privatePath));
	const identity = identityFrom(identityDir, privateKey, false);
	if (!existsSync(publicPath)) {
		writeFileSync(publicPath, createPublicKey(privateKey).export({ format: "pem", type: "spki" }), { mode: 0o644 });
	}
	return identity;
}
